import { readFile, writeFile } from "node:fs/promises";

// Keep the original vector paths as the editable source; ship a cached sprite.
const source = await readFile(new URL("../src/components/AboutMe/skillLogoPaths.ts", import.meta.url), "utf8");
const logos = [...source.matchAll(/\{ name: "([^"]+)", path: "([^"]+)" \}/g)];
if (!logos.length) throw new Error("No skill logo paths found");
const names = logos.map(([, name]) => name);
const symbols = logos.map(([, , path], index) => `<symbol id="skill-${index}" viewBox="0 0 24 24"><path d="${path}"/></symbol>`).join("\n");
await writeFile(new URL("../public/images/skill-logos.svg", import.meta.url), `<svg xmlns="http://www.w3.org/2000/svg">\n${symbols}\n</svg>\n`);
await writeFile(new URL("../src/components/AboutMe/skillLogoNames.ts", import.meta.url), `// Generated by scripts/generate-skill-logos.mjs from skillLogoPaths.ts.\nexport const SKILL_LOGO_NAMES = ${JSON.stringify(names, null, 2)};\n`);
console.log(`Generated ${names.length} skill logos`);
